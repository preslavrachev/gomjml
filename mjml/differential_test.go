// TestDifferential compares gomjml with MJML 4.16.1 over the differential corpus with
// compareWithReference, and each case's defect clusters with its record in
// testdata/differential/<source>.json. Sources without committed goldens are checked by digest
// only; scripts/differential.sh renders their references. See "Differential testing" in the
// README.
func TestDifferential(t *testing.T) {
	if *diffCaseName != "" {
		showCase(t, *diffCaseName)
		return
	}
	if *diffManifest != "" {
		writeManifest(t, *diffManifest)
		return
	}

	var results map[string]reference
	if *diffResults != "" {
		var err error
		if results, err = readResults(*diffResults); err != nil {
			t.Fatalf("reading reference results: %v", err)
		}
	} else if *diffUpdate {
		t.Fatal("-diff.update needs -diff.results; run scripts/differential.sh")
	}

	clusters, err := readKnownClusters()
	if err != nil {
		t.Fatal(err)
	}
	run := &differentialRun{clusters: clusters, results: results}
	for _, source := range differentialSources {
		t.Run(source.name, func(t *testing.T) { run.source(t, source) })
	}

	if results == nil {
		return
	}
	run.assignNewClusters()
	if *diffUpdate {
		if err := run.writeRecords(); err != nil {
			t.Fatal(err)
		}
	}
	report := run.report()
	if err := writeReport(*diffReport, report); err != nil {
		t.Fatal(err)
	}
	t.Logf("report written to %s", *diffReport)
	for _, cluster := range run.clusters {
		if cluster.Reason == "" && run.clusterCases[cluster.ID] > 0 {
			t.Errorf("cluster %s has no reason in known-clusters.json; triage it (signatures: %s)",
				cluster.ID, strings.Join(cluster.Signatures, "; "))
		}
	}
	if run.complete {
		for _, cluster := range run.clusters {
			if run.clusterCases[cluster.ID] == 0 {
				t.Errorf("known cluster %s matches no case; remove it from known-clusters.json", cluster.ID)
			}
		}
	}
}

